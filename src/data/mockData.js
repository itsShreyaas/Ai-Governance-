// Helper calculations to derive dashboard metrics directly from mock data
export const getGovernanceMetrics = (tools = mockAiTools, audits = mockAuditEvents) => {
  const totalTools = tools.length;
  const approvedTools = tools.filter((t) => t.approvalStatus === "Approved").length;
  const restrictedTools = tools.filter((t) => t.approvalStatus === "Restricted").length;
  const pendingTools = tools.filter((t) => t.approvalStatus === "Pending Review").length;

  const lowRiskCount = tools.filter((t) => t.riskLevel === "Low").length;
  const medRiskCount = tools.filter((t) => t.riskLevel === "Medium").length;
  const highRiskCount = tools.filter((t) => t.riskLevel === "High").length;

  const statusChartData = [
    { name: "Approved", value: approvedTools, color: "#1B4D3E" },
    { name: "Pending", value: pendingTools, color: "#D97706" },
    { name: "Restricted", value: restrictedTools, color: "#DC2626" },
  ];

  const riskChartData = [
    { level: "Low Risk", count: lowRiskCount, fill: "#15803D", percentage: Math.round((lowRiskCount / totalTools) * 100) },
    { level: "Medium Risk", count: medRiskCount, fill: "#D97706", percentage: Math.round((medRiskCount / totalTools) * 100) },
    { level: "High Risk", count: highRiskCount, fill: "#DC2626", percentage: Math.round((highRiskCount / totalTools) * 100) },
  ];

  const toolsNeedingReview = tools.filter(
    (t) => t.approvalStatus === "Pending Review" || t.riskLevel === "High"
  );

  return {
    totalTools,
    approvedTools,
    restrictedTools,
    pendingTools,
    lowRiskCount,
    medRiskCount,
    highRiskCount,
    statusChartData,
    riskChartData,
    toolsNeedingReview,
    recentAudits: audits.slice(0, 5),
  };
};
